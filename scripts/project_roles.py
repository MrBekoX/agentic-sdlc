#!/usr/bin/env python3
"""Project the shared role files (`agents/*.md`) into each runtime's agent format.

Usage:
  python3 scripts/project_roles.py --target cursor --check [--root <dir>]
  python3 scripts/project_roles.py --target cursor --write [--root <dir>]
  python3 scripts/project_roles.py --target antigravity --output <dir> [--root <dir>]

`agents/*.md` is the only source. The Cursor projection is committed as `cursor/agents/`, because
the Cursor installer and a team-marketplace import read the committed tree; `--check` fails when
that mirror differs from the generated bytes, and `--write` regenerates it. The Antigravity
projection is generated into a package at build time and is never committed.

Cursor rules: keep `name`, `description` and `model` verbatim, drop `tools`, and add
`readonly: true` and `permissionMode: readonly` when the role has no tool from WRITING_TOOLS.
Antigravity rules (agy 1.5.14): `tools` is a YAML list of agy runtime names (a comma string makes
the agy loader skip the agent), `subagent: true`, `mainAgent: false`, `model: inherit`, and
read-only roles add `inheritMcp: false`. A role model other than `inherit` is an error: agy model
names are not Claude's, so a pinned model is never silently replaced. agy has no grep or glob tool, so a read-only role reads
only the files the orchestrating skill names. The body is copied byte for byte in both.

Output: key=value lines, error=<code>:<detail> lines; exit 0 pass, 1 check failure or bad role,
2 usage error.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

WRITING_TOOLS = frozenset({"Write", "Edit", "Bash", "PowerShell", "NotebookEdit"})
# Claude tool -> agy runtime tool (names from a live agy 1.5.14 session and its bundled
# migrate-agent-settings skill; the web-doc names view_file/grep_search are not runtime names).
AGY_TOOLS = {
    "Read": "read_file", "Glob": "read_file", "Grep": "read_file",
    "WebFetch": "search_web", "WebSearch": "search_web",
    "Write": "write_file",
    "Edit": "edit_file", "MultiEdit": "edit_file",
    "Bash": "run_command", "PowerShell": "run_command",
}
AGY_ORDER = ("read_file", "search_web", "write_file", "edit_file", "run_command")
AGY_WRITE = frozenset({"write_file", "edit_file", "run_command"})
TARGETS = ("cursor", "antigravity")
MIRROR = {"cursor": "cursor/agents"}


class RoleError(Exception):
    """A role file the generator cannot project; the message is an error code."""


def parse_role(text: str) -> tuple:
    """(fields, body): the frontmatter `key: value` lines as a dict and the body after it."""
    if not text.startswith("---\n") or "\n---\n" not in text[3:]:
        raise RoleError("frontmatter_missing")
    head, body = text[4:].split("\n---\n", 1)
    fields = {}
    for line in head.splitlines():
        key, sep, _value = line.partition(":")
        if not sep or not key.strip():
            raise RoleError("frontmatter_line_invalid")
        fields[key.strip()] = line
    for required in ("name", "description", "model"):
        if required not in fields:
            raise RoleError(f"{required}_missing")
    return fields, body


def _tools(fields: dict) -> list:
    if "tools" not in fields:
        raise RoleError("tools_missing")
    value = fields["tools"].split(":", 1)[1]
    return [tool.strip() for tool in value.split(",") if tool.strip()]


def project_cursor(text: str) -> str:
    fields, body = parse_role(text)
    lines = [fields["name"], fields["description"], fields["model"]]
    if not set(_tools(fields)) & WRITING_TOOLS:
        lines += ["readonly: true", "permissionMode: readonly"]
    return "---\n" + "\n".join(lines) + "\n---\n" + body


def project_antigravity(text: str) -> str:
    fields, body = parse_role(text)
    model = fields["model"].split(":", 1)[1].strip()
    if model != "inherit":
        raise RoleError(f"model_unsupported:{model}")
    mapped = set()
    for tool in _tools(fields):
        if tool not in AGY_TOOLS:
            raise RoleError(f"unknown_tool:{tool}")
        mapped.add(AGY_TOOLS[tool])
    if not mapped:
        raise RoleError("tools_missing")
    tools = [tool for tool in AGY_ORDER if tool in mapped]
    lines = [fields["name"], fields["description"], "tools:"] + [f"  - {tool}" for tool in tools]
    lines += ["model: inherit", "subagent: true", "mainAgent: false"]
    if not mapped & AGY_WRITE:
        lines.append("inheritMcp: false")
    return "---\n" + "\n".join(lines) + "\n---\n" + body


PROJECTORS = {"cursor": project_cursor, "antigravity": project_antigravity}


def project_role(target: str, name: str, data: bytes) -> bytes:
    """Project one role file's bytes; RoleError names the file."""
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        raise RoleError(f"role_unreadable:{name}") from None
    try:
        return PROJECTORS[target](text).encode("utf-8")
    except RoleError as exc:
        raise RoleError(f"{exc}:{name}") from None


def generate(root, target: str) -> dict:
    """{file name: projected bytes} for every `agents/*.md` under root."""
    sources = sorted((Path(root) / "agents").glob("*.md"))
    if not sources:
        raise RoleError("roles_missing:agents")
    return {path.name: project_role(target, "agents/" + path.name, path.read_bytes()) for path in sources}


def check_mirror(root, target: str) -> list:
    root = Path(root)
    folder = MIRROR[target]
    generated = generate(root, target)
    present = {p.name for p in (root / folder).glob("*.md")}
    errors = [f"error=mirror_missing:{folder}/{name}" for name in sorted(set(generated) - present)]
    errors += [f"error=mirror_unexpected:{folder}/{name}" for name in sorted(present - set(generated))]
    errors += [f"error=mirror_drift:{folder}/{name}" for name in sorted(set(generated) & present)
               if (root / folder / name).read_bytes() != generated[name]]
    return errors


def _write(folder: Path, generated: dict, prune: bool) -> None:
    folder.mkdir(parents=True, exist_ok=True)
    if prune:
        for stale in folder.glob("*.md"):
            if stale.name not in generated:
                stale.unlink()
    for name, data in generated.items():
        (folder / name).write_bytes(data)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--target", choices=TARGETS, required=True)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="fail when the committed mirror drifted")
    mode.add_argument("--write", action="store_true", help="regenerate the committed mirror")
    mode.add_argument("--output", metavar="DIR", help="write the projection into DIR")
    parser.add_argument("--root", default=str(Path(__file__).resolve().parents[1]),
                        help="checkout holding agents/ (default: this repository)")
    args = parser.parse_args(argv)
    if (args.check or args.write) and args.target not in MIRROR:
        parser.error(f"--target {args.target} has no committed mirror; use --output")
    root = Path(args.root)
    try:
        if args.check:
            errors = check_mirror(root, args.target)
            for line in errors:
                print(line)
            print("project_roles_check=" + ("failed" if errors else "passed"))
            return 1 if errors else 0
        generated = generate(root, args.target)
        folder = root / MIRROR[args.target] if args.write else Path(args.output)
        _write(folder, generated, prune=args.write)
    except RoleError as exc:
        print(f"error={exc}")
        return 1
    print(f"project_roles_{args.target}={len(generated)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
