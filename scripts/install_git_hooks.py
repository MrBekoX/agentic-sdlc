#!/usr/bin/env python3
"""Install the effect-layer git hooks (pre-commit, commit-msg) into a repository.

WHY A GIT HOOK AT ALL
The PreToolUse command guards read the command STRING, and that layer is provably incomplete:
shell aliases and functions, `$PATH` shadowing, `eval` and variable indirection are resolved by
the shell after the hook has decided. Git runs a `pre-commit` hook on the OPERATION, after it has
already resolved its own alias table and after the shell has done quote removal, so the same guard
sees `git commit`, `git ci`, `g'i't commit` and a shell function named `git` identically.

WHAT THIS INSTALLER PROMISES
  * It never clobbers a hook it did not write. If a foreign `pre-commit` exists it refuses and
    tells you, because silently replacing someone's hook is a side effect a security tool must not
    have.
  * It is idempotent: re-running it produces a byte-identical hook.
  * `--uninstall` removes only hooks carrying our sentinel.
  * The generated hook FAILS OPEN, loudly, if the scanner is missing (a moved plugin must never
    wedge your commits) - it prints a warning rather than exiting non-zero.

WHAT IT DOES NOT PROMISE
`git commit --no-verify` skips it; that is documented git behaviour, not a defect. Nor does it see
commits made in another clone, or history rewrites. A client-side hook is a fast local backstop;
non-negotiable enforcement belongs server-side (pre-receive) or in CI.
"""
import argparse
import os
import stat
import subprocess
import sys
from pathlib import Path

SENTINEL = "agentic-sdlc-effect-layer-guard"
# Four hooks, because one flag used to disarm the whole layer and one common operation escaped it:
#   pre-commit         - staged content + credential filenames on an ordinary commit
#   pre-merge-commit   - `git merge` runs THIS, not pre-commit, so merge commits were unscanned
#   commit-msg         - the message (pre-commit runs before a message exists)
#   prepare-commit-msg - the only commit-path hook `--no-verify` does not suppress, and it can read
#                        both the staged index and the message file
HOOKS = ("pre-commit", "pre-merge-commit", "commit-msg", "prepare-commit-msg")
PLUGIN_ROOT = Path(__file__).resolve().parents[1]
SCANNER = PLUGIN_ROOT / "hooks" / "git-hook-scan.mjs"


def hook_body(name: str) -> str:
    """A POSIX-sh shim. Git for Windows ships sh, so one form works on every supported host."""
    scanner = str(SCANNER).replace("\\", "/")
    return (
        "#!/bin/sh\n"
        "# " + SENTINEL + "\n"
        "# Generated by scripts/install_git_hooks.py - re-run it to refresh, or use --uninstall.\n"
        "# Scans what git is ABOUT TO RECORD, so command-string tricks (aliases, eval, $PATH,\n"
        "# quoting) are irrelevant here. `git commit --no-verify` still skips it, by git's design.\n"
        'SCANNER="' + scanner + '"\n'
        'if [ ! -f "$SCANNER" ]; then\n'
        '  echo "agentic-sdlc: WARNING - guard scanner missing at $SCANNER; this commit was NOT scanned" >&2\n'
        "  exit 0\n"
        "fi\n"
        'if ! command -v node >/dev/null 2>&1; then\n'
        '  echo "agentic-sdlc: WARNING - node not found on PATH; this commit was NOT scanned" >&2\n'
        "  exit 0\n"
        "fi\n"
        'exec node "$SCANNER" ' + name + ' "$@"\n'
    )


def git_dir(repo: Path) -> Path:
    out = subprocess.run(["git", "rev-parse", "--git-dir"], cwd=str(repo),
                         capture_output=True, text=True, encoding="utf-8")
    if out.returncode != 0:
        raise SystemExit("not a git repository: " + str(repo))
    p = Path(out.stdout.strip())
    return p if p.is_absolute() else (repo / p)


def hooks_dir(repo: Path) -> Path:
    """Honour core.hooksPath, or git silently ignores anything written to .git/hooks."""
    out = subprocess.run(["git", "config", "--get", "core.hooksPath"], cwd=str(repo),
                         capture_output=True, text=True, encoding="utf-8")
    configured = out.stdout.strip()
    if configured:
        p = Path(configured)
        return p if p.is_absolute() else (repo / p)
    return git_dir(repo) / "hooks"


def is_ours(path: Path) -> bool:
    try:
        return SENTINEL in path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return False


def cmd_check(repo: Path) -> int:
    d = hooks_dir(repo)
    print("hooks_dir=" + str(d))
    print("scanner=" + str(SCANNER) + (" (present)" if SCANNER.is_file() else " (MISSING)"))
    for name in HOOKS:
        p = d / name
        if not p.exists():
            state = "absent"
        elif is_ours(p):
            state = "installed" if p.read_text(encoding="utf-8") == hook_body(name) else "installed-stale"
        else:
            state = "foreign (will not be touched)"
        print(name + "=" + state)
    return 0


def cmd_install(repo: Path) -> int:
    d = hooks_dir(repo)
    d.mkdir(parents=True, exist_ok=True)
    foreign = [n for n in HOOKS if (d / n).exists() and not is_ours(d / n)]
    if foreign:
        sys.stderr.write(
            "refusing to install: these hooks already exist and were not written by this tool:\n"
            + "".join("  " + str(d / n) + "\n" for n in foreign)
            + "Chain them yourself, or move them aside, then re-run.\n"
        )
        return 2
    for name in HOOKS:
        p = d / name
        body = hook_body(name)
        if p.exists() and p.read_text(encoding="utf-8") == body:
            print(name + "=unchanged")
            continue
        p.write_text(body, encoding="utf-8", newline="\n")
        p.chmod(p.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
        print(name + "=installed")
    return 0


def cmd_uninstall(repo: Path) -> int:
    d = hooks_dir(repo)
    for name in HOOKS:
        p = d / name
        if not p.exists():
            print(name + "=absent")
        elif is_ours(p):
            p.unlink()
            print(name + "=removed")
        else:
            print(name + "=foreign (left in place)")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--repo", default=".", help="repository to act on (default: cwd)")
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--check", action="store_true", help="report status (default)")
    g.add_argument("--install", action="store_true")
    g.add_argument("--uninstall", action="store_true")
    a = ap.parse_args()
    repo = Path(a.repo).resolve()
    if a.install:
        return cmd_install(repo)
    if a.uninstall:
        return cmd_uninstall(repo)
    return cmd_check(repo)


if __name__ == "__main__":
    raise SystemExit(main())
