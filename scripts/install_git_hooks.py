#!/usr/bin/env python3
"""Install the effect-layer git hooks (pre-commit, commit-msg) into a repository.

WHY A GIT HOOK AT ALL
The PreToolUse command guards read the command STRING, and that layer is provably incomplete:
shell aliases and functions, `$PATH` shadowing, `eval` and variable indirection are resolved by
the shell after the hook has decided. Git runs a `pre-commit` hook on the OPERATION, after it has
already resolved its own alias table and after the shell has done quote removal, so the same guard
sees `git commit`, `git ci`, `g'i't commit` and a shell function named `git` identically.

WHAT THIS INSTALLER PROMISES
  * It never clobbers a hook it did not write. If a foreign `pre-commit` exists it refuses and
    tells you, because silently replacing someone's hook is a side effect a security tool must not
    have.
  * It is idempotent: re-running it produces a byte-identical hook.
  * Ownership is recorded under this repository's git directory; `--uninstall` removes only a
    byte hash that this installer recorded. A copied sentinel or self-declared digest proves
    nothing.
  * A shared/external `core.hooksPath` requires `--allow-external-hooks-path` before any write or
    delete.
  * The generated hook FAILS OPEN, loudly, if the scanner is missing (a moved plugin must never
    wedge your commits) - it prints a warning rather than exiting non-zero.

WHAT IT DOES NOT PROMISE
`git commit --no-verify` skips `pre-commit` and `commit-msg`; Git still runs the installed
`prepare-commit-msg` backstop. No client hook sees commits made in another clone or server-side
history rewrites. Non-negotiable enforcement belongs in pre-receive policy or CI.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import shlex
import stat
import subprocess
import sys
from pathlib import Path

SENTINEL = "agentic-sdlc-effect-layer-guard"
DIGEST_PREFIX = "# agentic-sdlc-body-sha256: "
MANIFEST_NAME = "agentic-sdlc-hooks.json"
# Four hooks, because one flag used to disarm the whole layer and one common operation escaped it:
#   pre-commit         - staged content + credential filenames on an ordinary commit
#   pre-merge-commit   - `git merge` runs THIS, not pre-commit, so merge commits were unscanned
#   commit-msg         - the message (pre-commit runs before a message exists)
#   prepare-commit-msg - the only commit-path hook `--no-verify` does not suppress, and it can read
#                        both the staged index and the message file
HOOKS = ("pre-commit", "pre-merge-commit", "commit-msg", "prepare-commit-msg")
PLUGIN_ROOT = Path(__file__).resolve().parents[1]
SCANNER = PLUGIN_ROOT / "hooks" / "git-hook-scan.mjs"


def _unsigned_hook_body(name: str, *, safe_quote: bool) -> str:
    """Return the generated POSIX-sh shim without its integrity marker."""
    scanner = str(SCANNER).replace("\\", "/")
    assignment = "SCANNER=" + (shlex.quote(scanner) if safe_quote else '"' + scanner + '"')
    return (
        "#!/bin/sh\n"
        "# " + SENTINEL + "\n"
        "# Generated by scripts/install_git_hooks.py - re-run it to refresh, or use --uninstall.\n"
        "# Scans what git is ABOUT TO RECORD, so command-string tricks (aliases, eval, $PATH,\n"
        "# quoting) are irrelevant here. --no-verify skips pre-commit/commit-msg;\n"
        "# prepare-commit-msg remains an additional backstop by Git's design.\n"
        + assignment + "\n"
        'if [ ! -f "$SCANNER" ]; then\n'
        '  echo "agentic-sdlc: WARNING - guard scanner missing at $SCANNER; this commit was NOT scanned" >&2\n'
        "  exit 0\n"
        "fi\n"
        'if ! command -v node >/dev/null 2>&1; then\n'
        '  echo "agentic-sdlc: WARNING - node not found on PATH; this commit was NOT scanned" >&2\n'
        "  exit 0\n"
        "fi\n"
        'exec node "$SCANNER" ' + name + ' "$@"\n'
    )


def _body_digest(body: str) -> str:
    return hashlib.sha256(body.encode("utf-8")).hexdigest()


def hook_body(name: str) -> str:
    """A self-identifying POSIX-sh shim. Git for Windows ships sh."""
    unsigned = _unsigned_hook_body(name, safe_quote=True)
    marker = "# " + SENTINEL + "\n"
    return unsigned.replace(marker, marker + DIGEST_PREFIX + _body_digest(unsigned) + "\n", 1)


def _legacy_hook_body(name: str) -> str:
    """Exact pre-digest body accepted only for a one-time safe migration.

    Its embedded no-verify sentence is intentionally historical data; new hooks use the accurate
    per-hook wording produced by _unsigned_hook_body().
    """
    scanner = str(SCANNER).replace("\\", "/")
    return (
        "#!/bin/sh\n"
        "# " + SENTINEL + "\n"
        "# Generated by scripts/install_git_hooks.py - re-run it to refresh, or use --uninstall.\n"
        "# Scans what git is ABOUT TO RECORD, so command-string tricks (aliases, eval, $PATH,\n"
        "# quoting) are irrelevant here. `git commit --no-verify` still skips it, by git's design.\n"
        'SCANNER="' + scanner + '"\n'
        'if [ ! -f "$SCANNER" ]; then\n'
        '  echo "agentic-sdlc: WARNING - guard scanner missing at $SCANNER; this commit was NOT scanned" >&2\n'
        "  exit 0\n"
        "fi\n"
        'if ! command -v node >/dev/null 2>&1; then\n'
        '  echo "agentic-sdlc: WARNING - node not found on PATH; this commit was NOT scanned" >&2\n'
        "  exit 0\n"
        "fi\n"
        'exec node "$SCANNER" ' + name + ' "$@"\n'
    )


def _rev_parse_path(repo: Path, *args: str) -> Path:
    out = subprocess.run(["git", "rev-parse", *args], cwd=str(repo),
                         capture_output=True, text=True, encoding="utf-8")
    if out.returncode != 0:
        raise SystemExit("not a git repository: " + str(repo))
    p = Path(out.stdout.strip())
    return p if p.is_absolute() else (repo / p)


def git_dir(repo: Path) -> Path:
    return _rev_parse_path(repo, "--git-dir")


def git_common_dir(repo: Path) -> Path:
    """The git directory every worktree of this repository shares (the shared hooks live here)."""
    return _rev_parse_path(repo, "--git-common-dir")


def hooks_dir(repo: Path) -> Path:
    """The folder git runs hooks from, as git itself resolves it (`git rev-parse --git-path hooks`).

    That honours core.hooksPath (anything written to .git/hooks is otherwise ignored) with git's own
    rules: a leading `~/` is the user's home (read raw, it became a folder named `~` in the
    checkout), a relative value is relative to the top of the working tree (not to a subdirectory
    `--repo`), and a linked worktree uses the shared `.git/hooks`, not `.git/worktrees/<name>/hooks`.
    """
    return _rev_parse_path(repo, "--git-path", "hooks").resolve()


def ownership_manifest_path(repo: Path) -> Path:
    # One record per repository: the hooks it describes are shared by every worktree.
    return git_common_dir(repo).resolve() / MANIFEST_NAME


def _file_digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_ownership(repo: Path, expected_hooks_dir: Path) -> dict[str, str]:
    """Load only a well-formed, path-bound repository-local ownership record."""
    path = ownership_manifest_path(repo)
    if not path.is_file():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    if (
        not isinstance(data, dict)
        or data.get("version") != 1
        or data.get("hooks_dir") != str(expected_hooks_dir.resolve())
        or not isinstance(data.get("hooks"), dict)
    ):
        return {}
    return {
        name: digest
        for name, digest in data["hooks"].items()
        if name in HOOKS and isinstance(digest, str) and len(digest) == 64
    }


def save_ownership(repo: Path, hooks_path: Path, hashes: dict[str, str]) -> None:
    path = ownership_manifest_path(repo)
    payload = {
        "version": 1,
        "hooks_dir": str(hooks_path.resolve()),
        "hooks": {name: hashes[name] for name in HOOKS if name in hashes},
    }
    temp = path.with_name(path.name + ".tmp")
    temp.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    os.replace(temp, path)


def _is_below(path: Path, root: Path) -> bool:
    try:
        path.resolve().relative_to(root.resolve())
        return True
    except ValueError:
        return False


def _work_tree(repo: Path) -> Path:
    """The top of the working tree (`--repo` may be a subdirectory); a bare repository has none."""
    out = subprocess.run(["git", "rev-parse", "--show-toplevel"], cwd=str(repo),
                         capture_output=True, text=True, encoding="utf-8")
    top = out.stdout.strip()
    return Path(top) if out.returncode == 0 and top else repo


def _shared_hooks_path(repo: Path) -> bool:
    """True when the global or system configuration sets core.hooksPath to one fixed folder.

    `git config --show-scope` (git 2.26+) prints `<scope>\\t<value>`; older git fails and the
    location rule alone applies. A relative value resolves inside each repository, so it is not
    shared; an absolute or `~` value is one folder for every repository on the machine.
    """
    out = subprocess.run(["git", "config", "--show-scope", "--get", "core.hooksPath"], cwd=str(repo),
                         capture_output=True, text=True, encoding="utf-8")
    if out.returncode != 0 or "\t" not in out.stdout:
        return False
    scope, value = out.stdout.rstrip("\r\n").split("\t", 1)
    return scope in {"global", "system"} and (value.startswith("~") or Path(value).is_absolute()
                                              or value.startswith(("/", "\\")))


def external_hooks_path(repo: Path, path: Path) -> bool:
    """True for a hooks directory outside this checkout and its repository's git directories, or a
    fixed folder set by the global or system configuration: every repository on the machine shares
    it, even when it happens to sit inside this checkout (a dotfiles repository)."""
    if _shared_hooks_path(repo):
        return True
    roots = (repo, _work_tree(repo), git_dir(repo), git_common_dir(repo))
    return not any(_is_below(path, root) for root in roots)


def hook_state(path: Path, name: str, recorded_hash: str | None = None) -> str:
    """Classify a hook; only the repo-local manifest establishes mutable ownership."""
    # A symlink is never ours: a dangling one reads as missing to exists(), and writing the hook body
    # would follow it to a target outside the repository, past the external-path opt-in.
    if path.is_symlink():
        return "foreign"
    if not path.exists():
        return "absent"
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return "foreign"
    actual_hash = _file_digest(path)
    if recorded_hash:
        if actual_hash != recorded_hash:
            return "modified"
        return "current" if text == hook_body(name) else "stale"
    # Exact historical generator output may be adopted during install, but is not deleted until an
    # ownership manifest has been written. An arbitrary sentinel/self-digest body remains foreign.
    if text in {hook_body(name), _legacy_hook_body(name)}:
        return "adoptable"
    return "foreign"


def cmd_check(repo: Path) -> int:
    d = hooks_dir(repo)
    ownership = load_ownership(repo, d)
    print("hooks_dir=" + str(d))
    print("hooks_path_scope=" + ("external" if external_hooks_path(repo, d) else "repository"))
    print("ownership_manifest=" + str(ownership_manifest_path(repo)))
    print("scanner=" + str(SCANNER) + (" (present)" if SCANNER.is_file() else " (MISSING)"))
    for name in HOOKS:
        p = d / name
        state = hook_state(p, name, ownership.get(name))
        labels = {
            "absent": "absent",
            "current": "installed",
            "adoptable": "unclaimed-known-body (install to adopt; uninstall will not remove)",
            "stale": "installed-stale",
            "modified": "modified (will not be touched)",
            "foreign": "foreign (will not be touched)",
        }
        print(name + "=" + labels[state])
    return 0


def cmd_install(repo: Path, *, allow_external_hooks_path: bool = False) -> int:
    d = hooks_dir(repo)
    if external_hooks_path(repo, d) and not allow_external_hooks_path:
        sys.stderr.write(
            "refusing to install into external/shared core.hooksPath without "
            "--allow-external-hooks-path: " + str(d) + "\n"
        )
        return 2
    d.mkdir(parents=True, exist_ok=True)
    ownership = load_ownership(repo, d)
    refused = [
        n for n in HOOKS
        if hook_state(d / n, n, ownership.get(n)) in {"foreign", "modified"}
    ]
    if refused:
        sys.stderr.write(
            "refusing to install: these hooks are foreign or were modified after generation:\n"
            + "".join("  " + str(d / n) + "\n" for n in refused)
            + "Chain them yourself, or move them aside, then re-run.\n"
        )
        return 2
    for name in HOOKS:
        p = d / name
        body = hook_body(name)
        if hook_state(p, name, ownership.get(name)) == "current":
            print(name + "=unchanged")
            continue
        p.write_text(body, encoding="utf-8", newline="\n")
        p.chmod(p.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
        print(name + "=installed")
    save_ownership(repo, d, {name: _file_digest(d / name) for name in HOOKS})
    return 0


def cmd_uninstall(repo: Path, *, allow_external_hooks_path: bool = False) -> int:
    d = hooks_dir(repo)
    if external_hooks_path(repo, d) and not allow_external_hooks_path:
        sys.stderr.write(
            "refusing to uninstall from external/shared core.hooksPath without "
            "--allow-external-hooks-path: " + str(d) + "\n"
        )
        return 2
    ownership = load_ownership(repo, d)
    refused = False
    for name in HOOKS:
        p = d / name
        state = hook_state(p, name, ownership.get(name))
        if state == "absent":
            print(name + "=absent")
        elif state in {"current", "stale"}:
            p.unlink()
            print(name + "=removed")
        elif state == "modified":
            refused = True
            print(name + "=modified (left in place)")
        elif state == "adoptable":
            print(name + "=unclaimed-known-body (left in place)")
        else:
            print(name + "=foreign (left in place)")
    if not refused and ownership:
        ownership_manifest_path(repo).unlink(missing_ok=True)
    return 2 if refused else 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--repo", default=".", help="repository to act on (default: cwd)")
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--check", action="store_true", help="report status (default)")
    g.add_argument("--install", action="store_true")
    g.add_argument("--uninstall", action="store_true")
    ap.add_argument(
        "--allow-external-hooks-path",
        action="store_true",
        help="allow writes/deletes when core.hooksPath resolves outside this repository or names "
             "one fixed folder in the global/system configuration",
    )
    a = ap.parse_args()
    repo = Path(a.repo).resolve()
    if a.install:
        return cmd_install(repo, allow_external_hooks_path=a.allow_external_hooks_path)
    if a.uninstall:
        return cmd_uninstall(repo, allow_external_hooks_path=a.allow_external_hooks_path)
    return cmd_check(repo)


if __name__ == "__main__":
    raise SystemExit(main())
